/**
 * Trust vocabulary for prompt construction.
 *
 * The application distinguishes code-owned instructions (`system`,
 * `developer`) from data that may be attacker-influenced (`user-request`,
 * `retrieved`, `external`, `tool-output`, `agent-output`). Only the first
 * group is ever allowed to act as instructions; everything else is rendered
 * inside an explicit, attributed data envelope.
 */

export type TrustedTier = "system" | "developer";

export type UntrustedTier =
  | "user-request"
  | "retrieved"
  | "external"
  | "tool-output"
  | "agent-output";

export type TrustTier = TrustedTier | UntrustedTier;

export type TrustClass = "trusted" | "untrusted";

/** A piece of untrusted content plus the provenance needed to attribute it. */
export interface UntrustedContent {
  tier: UntrustedTier;
  /** Raw, potentially hostile content. Never concatenated into instructions. */
  content: string;
  /** Human-readable provenance, e.g. `document:<docId>` or `tool:recon.snapshot`. */
  source: string;
  /** Stable id used for correlation; generated when omitted. */
  id?: string;
  /** Non-sensitive, data-only metadata recorded alongside the segment. */
  metadata?: Readonly<Record<string, string | number | boolean>>;
  /** Per-segment cap; defaults to `PROMPT_LIMITS.untrustedChars`. */
  maxChars?: number;
}

/** The trusted, code-owned part of a prompt plus any untrusted data. */
export interface PromptSpec {
  /** Logical agent name (`recon`, `knowledge`, `report`, `orchestrator`). */
  agent: string;
  /** Trusted system instructions (code-owned, immutable). */
  system: string;
  /** Trusted developer instructions (code-owned, immutable). */
  developer: string;
  /** Trusted task framing generated by application code. */
  task?: string;
  /** Authenticated user request: authorized but untrusted for instruction purposes. */
  userRequest?: string;
  /** Retrieved documents, tool output, external HTTP, or other agents' output. */
  untrusted?: readonly UntrustedContent[];
}

export type DetectionCategory =
  | "instruction-override"
  | "role-impersonation"
  | "delimiter-escape"
  | "tool-directive"
  | "exfiltration"
  | "encoded-payload"
  | "unicode-obfuscation"
  | "policy-bypass";

export interface DetectionSignal {
  category: DetectionCategory;
  weight: number;
  /** Short, non-sensitive description of the matched structural/lexical signal. */
  evidence: string;
}

export interface DetectionResult {
  suspicious: boolean;
  score: number;
  signals: readonly DetectionSignal[];
}

/** Detection outcome for one untrusted segment (provenance preserved). */
export interface PromptDetection {
  id: string;
  tier: UntrustedTier;
  source: string;
  result: DetectionResult;
}

/** Metadata about a rendered prompt segment; never contains raw content. */
export interface PromptSegment {
  id: string;
  tier: TrustTier;
  trust: TrustClass;
  source: string;
  chars: number;
  suspicious: boolean;
  score: number;
}

export interface PromptAssembly {
  /** Final text handed to `ModelProvider.complete`. */
  prompt: string;
  /**
   * Structured, content-free metadata handed to the model provider. It records
   * the trust boundary, segment provenance and detection outcomes so adapters
   * can log/route without re-parsing the prompt.
   */
  context: Record<string, unknown>;
  segments: readonly PromptSegment[];
  detections: readonly PromptDetection[];
  suspicious: boolean;
}

/** Result of inspecting inbound content that is not (yet) in a prompt. */
export interface UntrustedInspection {
  tier: UntrustedTier;
  source: string;
  result: DetectionResult;
}
